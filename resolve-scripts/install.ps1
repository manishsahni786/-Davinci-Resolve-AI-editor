param(
  [string]$TargetRoot,
  [string]$DataRoot,
  [string]$LogsRoot,
  [switch]$Force
)

$ErrorActionPreference = "Stop"

$ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
if (-not $DataRoot -or $DataRoot.Trim() -eq "") {
  $DataRoot = Join-Path $ProjectRoot "data"
}
if (-not $LogsRoot -or $LogsRoot.Trim() -eq "") {
  $LogsRoot = Join-Path $ProjectRoot "logs"
}
$DataRoot = [System.IO.Path]::GetFullPath($DataRoot)
$LogsRoot = [System.IO.Path]::GetFullPath($LogsRoot)

if (-not $TargetRoot -or $TargetRoot.Trim() -eq "") {
  $Roaming = [Environment]::GetFolderPath("ApplicationData")
  $TargetRoot = Join-Path $Roaming "Blackmagic Design\DaVinci Resolve\Support\Fusion\Scripts\Utility\AI Video Editor"
}
$TargetRoot = [System.IO.Path]::GetFullPath($TargetRoot)

$UtilityRoot = Split-Path -Parent $TargetRoot
$RequestsDir = Join-Path $DataRoot "requests"
$ResponsesDir = Join-Path $DataRoot "responses"
$ArchiveDir = Join-Path $RequestsDir "archive"

foreach ($directory in @($TargetRoot, $UtilityRoot, $DataRoot, $RequestsDir, $ResponsesDir, $ArchiveDir, $LogsRoot)) {
  if (-not (Test-Path -LiteralPath $directory)) {
    New-Item -ItemType Directory -Path $directory -Force | Out-Null
  }
}

if (Test-Path -LiteralPath $TargetRoot) {
  $existing = Get-ChildItem -LiteralPath $TargetRoot -Force -ErrorAction SilentlyContinue
  if ($existing) {
    $timestamp = Get-Date -Format "yyyyMMdd-HHmmss"
    $backupParent = Join-Path $ProjectRoot "backups\resolve-scripts"
    if (-not (Test-Path -LiteralPath $backupParent)) {
      New-Item -ItemType Directory -Path $backupParent -Force | Out-Null
    }
    $backupRoot = Join-Path $backupParent ("AI Video Editor " + $timestamp)
    Copy-Item -LiteralPath $TargetRoot -Destination $backupRoot -Recurse -Force
    Write-Host "Backed up existing scripts to: $backupRoot"
  }
}

$libSource = Join-Path $PSScriptRoot "lib"
$libTarget = Join-Path $TargetRoot "lib"
if (Test-Path -LiteralPath $libTarget) {
  Remove-Item -LiteralPath $libTarget -Recurse -Force
}
New-Item -ItemType Directory -Path $libTarget -Force | Out-Null
Copy-Item -Path (Join-Path $libSource "*.lua") -Destination $libTarget -Force

Copy-Item -LiteralPath (Join-Path $PSScriptRoot "bridge.lua") -Destination (Join-Path $TargetRoot "bridge.lua") -Force
Copy-Item -LiteralPath (Join-Path $PSScriptRoot "diagnostics.lua") -Destination (Join-Path $TargetRoot "diagnostics.lua") -Force

$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$launchers = @(
  @{
    Name = "AI Video Editor Bridge.lua"
    File = "bridge.lua"
    Label = "Bridge"
  },
  @{
    Name = "AI Video Editor Diagnostics.lua"
    File = "diagnostics.lua"
    Label = "Diagnostics"
  }
)

foreach ($launcher in $launchers) {
  $launcherPath = Join-Path $UtilityRoot $launcher.Name
  $launcherContent = @"
-- Generated by AI Video Editor installer. Do not edit.
-- Resolve enumerates scripts directly under Utility; the implementation lives in a subfolder.
local function aivePublish(key, value)
  if type(fusion) == "userdata" or type(fusion) == "table" then
    pcall(function()
      fusion:SetPrefs(key, value)
      fusion:SavePrefs()
    end)
  end
end

AIVE_SCRIPT_DIR = [==[$TargetRoot]==]
aivePublish("Global.AIVEBridgeError", "")
aivePublish("Global.AIVEBridgeStage", "$($launcher.Label)-start")
local chunk, loadError = loadfile(AIVE_SCRIPT_DIR .. "\\$($launcher.File)")
if not chunk then
  aivePublish("Global.AIVEBridgeError", tostring(loadError))
  print("AI Video Editor $($launcher.Label) load failed: " .. tostring(loadError))
  return
end
local ok, message = pcall(chunk, AIVE_SCRIPT_DIR)
if not ok then
  aivePublish("Global.AIVEBridgeError", tostring(message))
  print("AI Video Editor $($launcher.Label) failed: " .. tostring(message))
else
  aivePublish("Global.AIVEBridgeStage", "$($launcher.Label)-done")
end
"@
  if (Test-Path -LiteralPath $launcherPath) {
    $previous = Get-Content -LiteralPath $launcherPath -Raw -ErrorAction SilentlyContinue
    if ($previous -and $previous -notmatch "Generated by AI Video Editor installer") {
      $backupParent = Join-Path $ProjectRoot "backups\resolve-launchers"
      if (-not (Test-Path -LiteralPath $backupParent)) {
        New-Item -ItemType Directory -Path $backupParent -Force | Out-Null
      }
      $backupPath = Join-Path $backupParent ($launcher.Name + "." + (Get-Date -Format "yyyyMMdd-HHmmss") + ".bak")
      Copy-Item -LiteralPath $launcherPath -Destination $backupPath -Force
      Write-Host "Backed up existing launcher to: $backupPath"
    }
  }
  [System.IO.File]::WriteAllText($launcherPath, $launcherContent, $utf8NoBom)
}

$configContent = @"
-- Generated by resolve-scripts/install.ps1. Do not edit unless your paths change.
return {
  projectRoot = [==[$ProjectRoot]==],
  dataDir = [==[$DataRoot]==],
  bridgeRoot = [==[$DataRoot]==],
  requestsDir = [==[$RequestsDir]==],
  responsesDir = [==[$ResponsesDir]==],
  archiveDir = [==[$ArchiveDir]==],
  logsDir = [==[$LogsRoot]==],
  protocolVersion = "1.0",
  source = "installer"
}
"@

$configPath = Join-Path $TargetRoot "bridge_config.lua"
[System.IO.File]::WriteAllText($configPath, $configContent, $utf8NoBom)

$readme = @"
AI Video Editor - Resolve Lua scripts
Installed: $(Get-Date -Format "yyyy-MM-dd HH:mm:ss")
Project root: $ProjectRoot
Data root: $DataRoot
Logs: $LogsRoot

In DaVinci Resolve:
  Workspace > Scripts > Utility > AI Video Editor Diagnostics
  Workspace > Scripts > Utility > AI Video Editor Bridge

The bridge processes ONE queued request. There is no background polling on Resolve Free.
"@
[System.IO.File]::WriteAllText((Join-Path $TargetRoot "README.txt"), $readme, $utf8NoBom)

Write-Host ""
Write-Host "AI Video Editor Lua scripts installed."
Write-Host "  Scripts: $TargetRoot"
Write-Host "  Requests: $RequestsDir"
Write-Host "  Responses: $ResponsesDir"
Write-Host "  Logs: $LogsRoot"
Write-Host ""
Write-Host "In Resolve, use: Workspace > Scripts > Utility > AI Video Editor Bridge"
Write-Host "Existing scripts in the Utility folder (including resolve_test.lua) were not modified."
